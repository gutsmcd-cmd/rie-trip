export function localeFor(lang: Lang): string {
  switch (lang) {
    case 'ja':
      return 'ja-JP';
    case 'es':
      return 'es-ES';
    case 'ca':
      return 'ca-ES';
    case 'ar':
      return 'ar-AE';
    default:
      return 'en-GB';
  }
}

